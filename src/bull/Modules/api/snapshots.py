"""Contract snapshots of modules and interfaces."""

from __future__ import annotations

import difflib
from collections.abc import Callable, Mapping
from pathlib import Path

from bull.Modules.api.approval import authorize
from bull.Modules.api.Contracts import ApiCheck, ApiSnapshots, Snapshot
from bull.Modules.foundation.Contracts import AppLayout, BullError, Files
from bull.Modules.memo.Contracts import InterfaceEntry, Memo, ModuleEntry
from bull.Modules.parts.Contracts import Parts
from bull.Modules.stacks.Contracts import StackRegistry
from bull.Modules.status.Contracts import StatusStore

_COMMENT = (
    "<!-- Generated by `bull api`; do not edit. A change here is a contract change. -->"
)
_FENCE = "```"


class LiveApiSnapshots(ApiSnapshots):
    """Snapshots read from the module's `Contracts/` folder (or an interface file) and
    stored as Markdown under `app.api_dir`; all stored-file I/O goes through `files`."""

    def __init__(
        self,
        files: Files,
        parts: Parts,
        stacks: StackRegistry,
        memo: Callable[[], Memo],
        store: StatusStore,
    ) -> None:
        self._files = files
        self._parts = parts
        self._stacks = stacks
        self._memo = memo
        self._store = store

    # --- modules ---------------------------------------------------------

    def current(self, app: AppLayout, module: str) -> Snapshot:
        return self._current(app, self._module(module))

    def check(self, app: AppLayout, module: str) -> ApiCheck:
        current = self.current(app, module)
        return self._check(module, self._module_path(app, module), current)

    def write(
        self, app: AppLayout, module: str, approved: str | None = None
    ) -> Path | None:
        entry = self._module(module)
        current = self._current(app, entry)
        return self._write(
            module,
            self._module_path(app, module),
            current,
            approved,
            entry.contract_changes,
        )

    # --- interfaces ------------------------------------------------------

    def check_interface(self, app: AppLayout, name: str) -> ApiCheck:
        entry = self._interface(name)
        current = self._interface_current(app, entry)
        return self._check(name, self._interface_path(app, name), current)

    def write_interface(
        self, app: AppLayout, name: str, approved: str | None = None
    ) -> Path | None:
        entry = self._interface(name)
        current = self._interface_current(app, entry)
        return self._write(
            name,
            self._interface_path(app, name),
            current,
            approved,
            entry.contract_changes,
        )

    # --- text form -------------------------------------------------------

    def render(self, snapshot: Snapshot) -> str:
        lines = [f"# {snapshot.name} contract", "", _COMMENT]
        for path, declarations in snapshot.files.items():
            lines += ["", f"## {path}", _FENCE, *declarations, _FENCE]
        return "\n".join(lines) + "\n"

    def parse(self, text: str) -> Snapshot:
        """Inverse of `render`: the heading names the snapshot; each `## <path>` is
        followed by a fenced block of declarations."""
        lines = text.splitlines()
        if not lines or not (
            lines[0].startswith("# ") and lines[0].endswith(" contract")
        ):
            raise BullError(
                "not a contract snapshot: missing the `# <Name> contract` heading"
            )
        name = lines[0][len("# ") : -len(" contract")]
        files: dict[str, tuple[str, ...]] = {}
        index = 1
        while index < len(lines):
            line = lines[index]
            index += 1
            if not line.startswith("## "):
                continue
            path = line[len("## ") :]
            if index >= len(lines) or lines[index] != _FENCE:
                raise BullError(f"contract snapshot: `## {path}` has no fenced block")
            index += 1
            declarations: list[str] = []
            while index < len(lines) and lines[index] != _FENCE:
                declarations.append(lines[index])
                index += 1
            if index >= len(lines):
                raise BullError(f"contract snapshot: unclosed block for `{path}`")
            index += 1
            files[path] = tuple(declarations)
        return Snapshot(name, files)

    # --- helpers ---------------------------------------------------------

    def _module(self, module: str) -> ModuleEntry:
        for entry in self._memo().modules:
            if entry.name == module:
                return entry
        raise BullError(
            f"unknown module {module}", "check the module name in docs/outline.md"
        )

    def _interface(self, name: str) -> InterfaceEntry:
        for entry in self._memo().interfaces:
            if entry.name == name:
                return entry
        raise BullError(
            f"unknown interface {name}",
            "check the name in the memo's `## Interfaces` section",
        )

    def _current(self, app: AppLayout, entry: ModuleEntry) -> Snapshot:
        part = self._parts.get(app, entry.part)
        module_dir = self._parts.module_src(part, entry.name)
        contracts = module_dir / "Contracts"
        if not contracts.is_dir():
            raise BullError(
                f"{entry.name} has no Contracts/ folder ({contracts})",
                "create the module's Contracts/ folder",
            )
        stack = self._stacks.get(part.stack)
        sources = sorted(
            (p for p in contracts.rglob(stack.manifest.source_glob) if p.is_file()),
            key=lambda p: p.relative_to(module_dir).as_posix(),
        )
        files = {
            path.relative_to(module_dir).as_posix(): tuple(
                stack.readers.contract_declarations(path)
            )
            for path in sources
        }
        return Snapshot(entry.name, files)

    def _interface_current(self, app: AppLayout, entry: InterfaceEntry) -> Snapshot:
        path = app.root / entry.file
        text = self._files.read_text(path)
        if text is None:
            raise BullError(
                f"interface {entry.name}: file {entry.file} not found",
                "create the file or fix its path in the memo's `## Interfaces`",
            )
        return Snapshot(entry.name, {entry.file: tuple(text.splitlines())})

    @staticmethod
    def _module_path(app: AppLayout, module: str) -> Path:
        return app.api_dir / f"{module}.md"

    @staticmethod
    def _interface_path(app: AppLayout, name: str) -> Path:
        return app.api_dir / "interfaces" / f"{name}.md"

    def _check(self, name: str, path: Path, current: Snapshot) -> ApiCheck:
        stored = self._files.read_text(path)
        if stored is None:
            return ApiCheck(
                name, False, False, f"no snapshot: run `bull api {name} --write`"
            )
        text = self.render(current)
        if stored == text:
            return ApiCheck(name, True, True, "")
        diff = difflib.unified_diff(
            stored.splitlines(),
            text.splitlines(),
            fromfile="stored",
            tofile="current",
            lineterm="",
        )
        return ApiCheck(name, False, True, "\n".join(diff) + "\n")

    def _write(
        self,
        name: str,
        path: Path,
        current: Snapshot,
        approved: str | None,
        contract_changes: Mapping[str, str],
    ) -> Path | None:
        text = self.render(current)
        stored = self._files.read_text(path)
        if stored == text:
            return None
        if stored is not None:
            authorize(name, approved, self._store, contract_changes)
        self._files.write_atomic(path, text)
        return path
